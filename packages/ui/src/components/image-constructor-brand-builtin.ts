function svgUrl(viewBox: string, paths: LogoPath[], color: string): string {
  const body = paths
    .map(
      ([d, rule]) =>
        `<path d="${d}" fill="${color}"${rule ? ` fill-rule="${rule}" clip-rule="${rule}"` : ''}/>`,
    )
    .join('');
  const [, , w, h] = viewBox.split(' ');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${viewBox}">${body}</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

