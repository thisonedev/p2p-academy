// Writes contract/ipc.json from shared/ipc-channels.cjs, shared/ipc-push-channels.cjs,
// the @academy/validation schemas they name, and ERROR_CODES from @academy/validation/errors.
// --check exits 1 when the file is stale.
//
// Usage: node scripts/ipc-contract.mjs [--check]
// Needs a built @academy/validation (pnpm --filter @academy/validation build).

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const contractFile = path.join(desktopRoot, 'contract', 'ipc.json');

export async function renderIpcContract() {
  const require = createRequire(import.meta.url);
  const channels = require('../shared/ipc-channels.cjs');
  const pushChannels = require('../shared/ipc-push-channels.cjs');
  const validation = await import('@academy/validation');
  const { ERROR_CODES } = await import('@academy/validation/errors');

  const invoke = {};
  const defs = {};
  for (const channel of Object.keys(channels).sort()) {
    const schemaName = channels[channel];
    invoke[channel] = { payload: schemaName === null ? null : `#/$defs/${schemaName}` };
    if (schemaName === null || defs[schemaName]) continue;
    const schema = validation[schemaName];
    if (!schema) throw new Error(`${channel}: @academy/validation has no export ${schemaName}`);
    // Input shape: what the renderer sends before refinements run in main.
    const { $schema: _drop, ...json } = schema.toJSONSchema({ io: 'input', unrepresentable: 'any' });
    defs[schemaName] = json;
  }

  const contract = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'P2P Academy desktop IPC contract',
    description:
      'Generated by apps/desktop/scripts/ipc-contract.mjs. Do not edit by hand. Payloads are the input shape; refinements run in main.',
    invoke,
    push: [...pushChannels].sort(),
    errors: Object.fromEntries(Object.keys(ERROR_CODES).sort().map((code) => [code, ERROR_CODES[code]])),
    $defs: Object.fromEntries(Object.keys(defs).sort().map((name) => [name, defs[name]])),
  };
  return `${JSON.stringify(contract, null, 2)}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const content = await renderIpcContract();
  const label = path.relative(desktopRoot, contractFile);
  if (process.argv.includes('--check')) {
    let existing = null;
    try {
      existing = readFileSync(contractFile, 'utf8');
    } catch {
      // A missing file counts as stale.
    }
    if (existing !== content) {
      console.error(
        `${label} is ${existing === null ? 'missing' : 'out of date'}. Run 'pnpm ipc:contract' and commit the result.`,
      );
      process.exit(1);
    }
    console.log(`${label} is current`);
  } else {
    mkdirSync(path.dirname(contractFile), { recursive: true });
    writeFileSync(contractFile, content);
    console.log(`wrote ${label}`);
  }
}
